"""Make the hosa27 VOICE PACK: one audio file per instruction, so every participant hears the
identical, natural-sounding voice (better than the iPad's robotic default, and more standardized).

Two ways to make it:

  A) A natural Mac voice (recommended quick option)
     1. Download a free "Premium" voice: System Settings > Accessibility > Spoken Content >
        System Voice > Manage Voices… > English (US) > tick "Ava (Premium)" (or Zoe / Evan / Nathan Premium).
     2. python3 tools/make_voice_audio.py                 (picks the best installed voice automatically)
        python3 tools/make_voice_audio.py --voice "Zoe (Premium)" --rate 135

  B) Your OWN recorded voice (most natural)
     1. python3 tools/make_voice_audio.py --script-only   -> writes app/audio/RECORDING_SCRIPT.md
     2. Record each line (Voice Memos / QuickTime), save as the listed file name (e.g. orient_day.m4a)
        into app/audio/own/
     3. python3 tools/make_voice_audio.py --own           (your files are used; any missing line uses a Mac voice)

Other:  --list-voices   show installed English voices
        --remove        delete the pack (go back to the iPad's built-in voice)

After making the pack: bump CACHE in app/sw.js and re-upload the app so iPads get the new audio.
"""
import argparse
import json
import re
import subprocess
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
AUDIO = APP / "audio"
OWN = AUDIO / "own"
TASKS = APP / "tasks.js"
NOVELTY = re.compile(r"^(Albert|Bad News|Bahh|Bells|Boing|Bubbles|Cellos|Wobble|Good News|Jester|Organ|Superstar|"
                     r"Trinoids|Whisper|Zarvox|Junior|Ralph|Fred|Kathy|Eddy|Flo|Grandma|Grandpa|Reed|Rocko|Sandy|Shelley)\b")


def load_tasks():
    jxa = f'''
    const src = $.NSString.stringWithContentsOfFileEncodingError("{TASKS}", $.NSUTF8StringEncoding, null).js;
    eval(src + "; JSON.stringify({{steps: STEPS, letters: LETTERS}})");
    '''
    out = subprocess.run(["osascript", "-l", "JavaScript", "-e", jxa], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def english_voices():
    out = subprocess.run(["say", "-v", "?"], capture_output=True, text=True).stdout
    voices = []
    for line in out.splitlines():
        m = re.match(r"^(.+?)\s+(en_[A-Z]{2})\s+#", line)
        if m and not NOVELTY.match(m.group(1).strip()):
            voices.append((m.group(1).strip(), m.group(2)))
    return voices


def best_voice():
    vs = english_voices()
    def rank(v):
        name, lang = v
        return (0 if "Premium" in name else 1 if "Enhanced" in name else 2 if name in ("Samantha", "Ava", "Zoe", "Evan") else 3,
                0 if lang == "en_US" else 1)
    return sorted(vs, key=rank)[0][0] if vs else "Samantha"


def split_sentences(text):
    """Same rule as the app (app.js splitSentences) so subtitles match the audio files exactly."""
    return [x.strip() for x in re.findall(r"[^.!?]+[.!?]*\s*", text or "") if x.strip()]


def step_text(step, silence=True):
    """Text spoken for one step: the instruction, then any words/digits/sentence with pauses."""
    text = step.get("say", "")
    seq = step.get("sequence")
    if seq:
        gap = max(300, int(step.get("sequenceGapMs", 1000)) - 350)
        if silence:
            text += " [[slnc 700]] " + f" [[slnc {gap}]] ".join(seq)
        else:
            text += "  (pause)  " + "  (pause 1 second)  ".join(seq)
    return text


def say_to_file(text, out, voice, rate):
    subprocess.run(["say", "-v", voice, "-r", str(rate), "-o", str(out),
                    "--file-format=m4af", "--data-format=aac", text], check=True)


def write_script(data):
    lines = ["# hosa27 voice recording script", "",
             "Record each line in a quiet room, at a calm, slightly slow pace, in a friendly voice.",
             "Save each recording with the exact file name into `app/audio/own/` (`.m4a` from Voice Memos is fine).",
             "Where it says (pause 1 second), pause for about one second between items.", "",
             "| File name | Say exactly |", "|---|---|"]
    for st in data["steps"]:
        if st.get("say"):
            lines.append(f"| `{st['id']}.m4a` | {step_text(st, silence=False)} |")
    (AUDIO / "RECORDING_SCRIPT.md").write_text("\n".join(lines) + "\n")
    print("wrote", AUDIO / "RECORDING_SCRIPT.md")


def write_manifest(rec, letters, info, files):
    js = ("// GENERATED by tools/make_voice_audio.py - do not edit by hand.\n"
          f"Object.assign(AUDIO_PACK_INFO, {json.dumps(info)});\n"
          f"Object.assign(RECORDED_AUDIO, {json.dumps(rec, indent=1)});\n"
          f"Object.assign(LETTER_AUDIO, {json.dumps(letters, indent=1)});\n")
    (AUDIO / "audio_manifest.js").write_text(js)
    (AUDIO / "audio_files.json").write_text(json.dumps(sorted(files), indent=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", help='Mac voice name, e.g. "Ava (Premium)" (default: best installed)')
    ap.add_argument("--rate", type=int, default=135, help="words per minute (default 135 = calm and slow; normal speech ~175)")
    ap.add_argument("--own", action="store_true", help="use your own recordings from app/audio/own/")
    ap.add_argument("--script-only", action="store_true", help="only write the recording script")
    ap.add_argument("--list-voices", action="store_true")
    ap.add_argument("--remove", action="store_true", help="remove the voice pack")
    args = ap.parse_args()
    AUDIO.mkdir(parents=True, exist_ok=True)

    if args.list_voices:
        for name, lang in english_voices():
            print(f"  {name:28s} {lang}{'   <- natural' if 'Premium' in name or 'Enhanced' in name else ''}")
        print('\nNo "(Premium)" voices? Download one: System Settings > Accessibility > Spoken Content > System Voice > Manage Voices…')
        return
    if args.remove:
        for f in AUDIO.glob("*.m4a"):
            f.unlink()
        write_manifest({}, {}, {}, [])
        print("Voice pack removed - the app will use the device's built-in voice.")
        return

    data = load_tasks()
    write_script(data)
    if args.script_only:
        return

    voice = args.voice or best_voice()
    if "Premium" not in voice and "Enhanced" not in voice and not args.own:
        print(f'NOTE: using "{voice}", a basic voice. For a much more natural sound, download a Premium voice first '
              f"(see --list-voices) and run this again.")
    # remove old generated files first (never touches app/audio/own/)
    for f in AUDIO.glob("*.m4a"):
        f.unlink()
    rec, letters, files, own_used = {}, {}, [], 0
    for st in data["steps"]:
        if not st.get("say"):
            continue
        own_file = OWN / f"{st['id']}.m4a"
        if args.own and own_file.exists():
            # your own single recording of the whole step (instruction + any list, as in RECORDING_SCRIPT.md)
            rec[st["id"]] = {"src": f"audio/own/{own_file.name}", "includesSequence": True, "own": True}
            files.append(f"own/{own_file.name}"); own_used += 1
        else:
            parts = []
            for n, sentence in enumerate(split_sentences(st["say"])):
                name = f"{st['id']}__p{n}.m4a"
                say_to_file(sentence, AUDIO / name, voice, args.rate)
                parts.append({"text": sentence, "src": f"audio/{name}"}); files.append(name)
            entry = {"parts": parts}
            if st.get("sequence"):
                seq = []
                for n, item in enumerate(st["sequence"]):
                    name = f"{st['id']}__q{n}.m4a"
                    say_to_file(item, AUDIO / name, voice, args.rate)
                    seq.append(f"audio/{name}"); files.append(name)
                entry["seq"] = seq
                # the gap after each item; item audio itself lasts ~0.4-0.6 s
                entry["seqGapMs"] = max(250, int(st.get("sequenceGapMs", 1000)) - 450)
            rec[st["id"]] = entry
        print(f"  ✓ {st['id']}")
    # (no letter files: since v0.6.0 the letter-tap task shows the letters on screen instead of speaking them)
    info = {"voice": (f"own recordings ({own_used} files) + {voice}" if args.own else voice),
            "rate": args.rate, "created": datetime.now().isoformat(timespec="seconds")}
    write_manifest(rec, letters, info, files)
    print(f"\nVoice pack ready: {len(rec)} instructions ({len(files)} audio files) ({info['voice']}).")
    print("Next: bump CACHE in app/sw.js, refresh the app (and re-upload it for the iPads).")


if __name__ == "__main__":
    main()
